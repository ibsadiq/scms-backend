class Receipt(models.Model):
    """
    Records incoming payments from students/parents.
    Updated to support fee assignment tracking.
    """
    receipt_number = models.IntegerField(unique=True, blank=True, null=True)
    date = models.DateField(auto_now_add=True)
    payer = models.CharField(max_length=255, default="Unknown")
    student = models.ForeignKey(
        Student,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='receipts'
    )
    amount = models.DecimalField(max_digits=10, decimal_places=2)
    paid_through = models.CharField(
        max_length=20,
        choices=PaymentThrough.choices,
        default=PaymentThrough.CASH
    )
    term = models.ForeignKey(
        Term,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='receipts'
    )
    payment_date = models.DateField(default=timezone.now)
    reference_number = models.CharField(
        max_length=100,
        blank=True,
        null=True,
        help_text="External reference number (bank ref, mobile money ref, etc.)"
    )
    status = models.CharField(
        max_length=20,
        choices=PaymentStatus.choices,
        default=PaymentStatus.COMPLETED
    )
    received_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        related_name='received_receipts'
    )
    remarks = models.TextField(blank=True, null=True)

    class Meta:
        ordering = ['-date', '-receipt_number']
        constraints = [
            models.CheckConstraint(condition=models.Q(amount__gt=0), name='finance_receipt_amount_positive'),
        ]
        indexes = [
            models.Index(fields=['student', 'term']),
            models.Index(fields=['receipt_number']),
            models.Index(fields=['date']),
        ]

    def __str__(self):
        return f"Receipt #{self.receipt_number} - {self.payer} - ₦{self.amount:,.2f}"

    def clean(self):
        if self.amount <= 0:
            raise ValidationError("Amount must be a positive value.")

    def save(self, *args, **kwargs):
        if hasattr(self, "payment_date") and hasattr(self.payment_date, "date") and callable(self.payment_date.date):
            self.payment_date = self.payment_date.date()

        if self.receipt_number:
            return super().save(*args, **kwargs)

        # Lock a stable PostgreSQL advisory key because an empty queryset has
        # no row for select_for_update() to lock.
        with transaction.atomic():
            with connection.cursor() as cursor:
                cursor.execute(
                    "SELECT pg_advisory_xact_lock(hashtext(%s))",
                    [f"{connection.schema_name}:finance:receipt-number"],
                )
            if not self.receipt_number:
                last_receipt = Receipt.objects.order_by("-receipt_number").first()
                self.receipt_number = (
                    (last_receipt.receipt_number + 1) if last_receipt else 1
                )
            return super().save(*args, **kwargs)

    @transaction.atomic
    def delete(self, *args, **kwargs):
        locked_receipt = Receipt.objects.select_for_update().get(pk=self.pk)
        assignment_ids = list(
            locked_receipt.fee_allocations.order_by()
            .values_list("fee_assignment_id", flat=True)
            .distinct()
        )
        assignments = list(
            StudentFeeAssignment.objects.select_for_update()
            .filter(pk__in=assignment_ids)
            .order_by("pk")
        )
        for assignment in assignments:
            allocated = locked_receipt.fee_allocations.filter(
                fee_assignment=assignment
            ).aggregate(total=Sum("amount"))["total"] or Decimal("0.00")
            assignment.amount_paid -= allocated
            assignment.full_clean()
            assignment.save(update_fields=("amount_paid",))
        return super().delete(*args, **kwargs)

    @property
    def allocated_amount(self):
        """Amount allocated to specific fee assignments."""
        return self.fee_allocations.aggregate(
            total=Sum('amount')
        )['total'] or Decimal('0.00')

    @property
    def unallocated_amount(self):
        """Amount not yet allocated to any fee."""
        return self.amount - self.allocated_amount


class FeePaymentAllocation(models.Model):
    """
    Links receipts to specific fee assignments.
    Allows one receipt to pay multiple fees, or multiple receipts to pay one fee.
    This replaces the old PaymentRecord model.
    """
    receipt = models.ForeignKey(
        Receipt,
        on_delete=models.CASCADE,
        related_name='fee_allocations'
    )
    fee_assignment = models.ForeignKey(
        StudentFeeAssignment,
        on_delete=models.PROTECT,
        related_name='payment_allocations'
    )
    amount = models.DecimalField(
        max_digits=10,
        decimal_places=2,
        help_text="Amount of this receipt allocated to this fee"
    )
    allocated_date = models.DateTimeField(auto_now_add=True)
    allocated_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True
    )

    class Meta:
        ordering = ['-allocated_date']
        constraints = [
            models.CheckConstraint(condition=models.Q(amount__gt=0), name='finance_allocation_amount_positive'),
        ]
        indexes = [
            models.Index(fields=['receipt', 'fee_assignment']),
        ]

    def __str__(self):
        return f"Receipt #{self.receipt.receipt_number} → {self.fee_assignment} (₦{self.amount:,.2f})"

    def clean(self):
        if self.amount <= 0:
            raise ValidationError("Allocation amount must be positive.")

        if self.amount > self.fee_assignment.balance:
            raise ValidationError(
                f"Cannot allocate ₦{self.amount} - fee balance is only ₦{self.fee_assignment.balance}"
            )

        # Check receipt doesn't over-allocate
        current_allocated = self.receipt.fee_allocations.exclude(
            pk=self.pk
        ).aggregate(total=Sum('amount'))['total'] or Decimal('0.00')

        if current_allocated + self.amount > self.receipt.amount:
            raise ValidationError(
                f"Cannot allocate ₦{self.amount} - only ₦{self.receipt.amount - current_allocated} remaining"
            )

    @transaction.atomic
    def save(self, *args, **kwargs):
        if self.pk:
            original = FeePaymentAllocation.objects.get(pk=self.pk)
            immutable = ("receipt_id", "fee_assignment_id", "amount")
            if any(getattr(original, field) != getattr(self, field) for field in immutable):
                raise ValidationError("Posted fee allocations are immutable; reverse and recreate the allocation.")
            return super().save(*args, **kwargs)

        receipt = Receipt.objects.select_for_update().get(pk=self.receipt_id)
        assignment = StudentFeeAssignment.objects.select_for_update().get(pk=self.fee_assignment_id)
        self.receipt = receipt
        self.fee_assignment = assignment

        if receipt.student_id and receipt.student_id != assignment.student_id:
            raise ValidationError("A receipt can only be allocated to fees for the same student.")

        self.full_clean()
        result = super().save(*args, **kwargs)
        assignment.amount_paid += self.amount
        assignment.last_payment_date = timezone.now()
        assignment.full_clean()
        assignment.save(update_fields=("amount_paid", "last_payment_date"))
        return result

    @transaction.atomic
    def delete(self, *args, **kwargs):
        allocation = FeePaymentAllocation.objects.select_for_update().get(pk=self.pk)
        assignment = StudentFeeAssignment.objects.select_for_update().get(
            pk=allocation.fee_assignment_id
        )
        assignment.amount_paid -= allocation.amount
        assignment.full_clean()
        assignment.save(update_fields=("amount_paid",))
        return super().delete(*args, **kwargs)


